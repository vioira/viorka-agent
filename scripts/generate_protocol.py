#!/usr/bin/env python3
"""Deterministic Go models from the canonical JSON Schema. No network fetches."""
import argparse,hashlib,json,subprocess
from pathlib import Path
root=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('--output',type=Path,default=root/'protocol/v1/models.gen.go');p.add_argument('--check',action='store_true');p.add_argument('--schema',type=Path,default=root/'api/agent/v1/envelope.schema.json');a=p.parse_args()
source=a.schema.read_bytes();s=json.loads(source)
def name(k):return ''.join({'id':'ID','os':'OS','sha256':'SHA256','cpu':'CPU','cpus':'CPUs','rx':'RX','tx':'TX'}.get(x,x.title()) for x in k.split('_'))
def typ(v):
 if '$ref' in v:return '*'+v['$ref'].split('/')[-1]
 if v.get('format')=='date-time':return 'time.Time'
 if v['type']=='array':return '[]'+typ(v['items'])
 return {'string':'string','integer':'uint64','number':'float64','object':'json.RawMessage'}[v['type']]
text='// Code generated by scripts/generate_protocol.py; DO NOT EDIT.\n// Schema SHA256: '+hashlib.sha256(source).hexdigest()+'\npackage v1\nimport("encoding/json";"time")\nconst Version = '+json.dumps(s['properties']['version']['const'])+'\n'
for title,v in [('Envelope',s),*s['$defs'].items()]:
 text+='type '+title+' struct {\n'
 for k,prop in v['properties'].items():
  t=typ(prop);optional=k not in v['required']
  if optional and t in ('uint64','float64'):t='*'+t
  text+=name(k)+' '+t+' `json:"'+k+(',omitempty' if optional else '')+'"`\n'
 text+='}\n'
text+='const (TaskQueued="queued";TaskDispatched="dispatched";TaskAccepted="accepted";TaskRunning="running";TaskSucceeded="succeeded";TaskFailed="failed";TaskRolledBack="rolled_back")\n'
formatted=subprocess.run(['gofmt'],input=text,text=True,capture_output=True,check=True).stdout
if a.check:
 if not a.output.exists() or a.output.read_text()!=formatted:raise SystemExit('generated protocol is stale: '+str(a.output))
else:a.output.parent.mkdir(parents=True,exist_ok=True);a.output.write_text(formatted)
